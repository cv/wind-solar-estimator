// Versions the site's own JS and CSS URLs by content, so browsers never mix cached
// files from different releases (GitHub Pages lets browsers cache each file for hours).
// Rewrites the marked block in index.html; `npm test` fails if it's out of date.
//
//   npm run stamp

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const START = "<!-- asset versions: generated by `npm run stamp` from file contents; don't edit by hand -->";
const END = "<!-- /asset versions -->";

const version = (path) => createHash("sha256").update(readFileSync(ROOT + path)).digest("hex").slice(0, 10);

/** The block index.html should contain for the current files. */
export function expectedBlock() {
  const modules = readdirSync(ROOT + "js").filter((f) => f.endsWith(".js") && f !== "app.js").sort();
  const imports = modules.map((f) => `      "./js/${f}": "./js/${f}?v=${version(`js/${f}`)}"`).join(",\n");
  return [
    START,
    `  <link rel="stylesheet" href="css/style.css?v=${version("css/style.css")}">`,
    `  <script type="importmap">`,
    `    { "imports": {`,
    imports,
    `    } }`,
    `  </script>`,
    `  <script type="module" src="js/app.js?v=${version("js/app.js")}"></script>`,
    `  ${END}`,
  ].join("\n");
}

/** The block currently in index.html (null if the markers are missing). */
export function currentBlock(html = readFileSync(ROOT + "index.html", "utf8")) {
  const a = html.indexOf(START), b = html.indexOf(END);
  return a < 0 || b < a ? null : html.slice(a, b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = readFileSync(ROOT + "index.html", "utf8");
  const old = currentBlock(html);
  if (!old) throw new Error("index.html has no asset-versions block");
  const next = expectedBlock();
  if (old === next) console.log("index.html asset versions are up to date");
  else { writeFileSync(ROOT + "index.html", html.replace(old, next)); console.log("index.html asset versions updated"); }
}
